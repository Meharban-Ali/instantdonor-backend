-- 1. Table users
CREATE TABLE users (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamp without time zone DEFAULT NULL,
    email varchar(150) NOT NULL UNIQUE,
    is_active boolean NOT NULL,
    last_login_at timestamp without time zone DEFAULT NULL,
    name varchar(100) NOT NULL,
    password varchar(255) NOT NULL,
    phone varchar(15) NOT NULL,
    updated_at timestamp without time zone DEFAULT NULL
);
CREATE INDEX idx_user_email ON users (email);
CREATE UNIQUE INDEX idx_users_email_lower ON users (LOWER(email));

-- 2. Table user_roles
CREATE TABLE user_roles (
    user_id bigint NOT NULL,
    role varchar(20) NOT NULL,
    PRIMARY KEY (user_id, role),
    CONSTRAINT fk_ur_user FOREIGN KEY (user_id) REFERENCES users (id)
);

-- 3. Table donor_profiles
CREATE TABLE donor_profiles (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    blood_group varchar(20) NOT NULL,
    city varchar(50) NOT NULL,
    created_at timestamp without time zone DEFAULT NULL,
    is_available boolean NOT NULL,
    last_donation_date date DEFAULT NULL,
    latitude decimal(10,8) NOT NULL,
    longitude decimal(11,8) NOT NULL,
    next_eligible_date date DEFAULT NULL,
    reliability_score decimal(5,2) NOT NULL,
    response_rate decimal(5,2) NOT NULL,
    state varchar(50) NOT NULL,
    total_donations int NOT NULL,
    updated_at timestamp without time zone DEFAULT NULL,
    user_id bigint NOT NULL UNIQUE,
    CONSTRAINT fk_dp_user FOREIGN KEY (user_id) REFERENCES users (id)
);
CREATE INDEX idx_donor_user ON donor_profiles (user_id);
CREATE INDEX idx_donor_blood_group ON donor_profiles (blood_group);
CREATE INDEX idx_donor_city ON donor_profiles (city);
CREATE INDEX idx_donor_available ON donor_profiles (is_available);

-- 4. Table blood_requests
CREATE TABLE blood_requests (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    additional_info text DEFAULT NULL,
    blood_group varchar(20) NOT NULL,
    city varchar(100) NOT NULL,
    contact_phone varchar(15) NOT NULL,
    created_at timestamp without time zone DEFAULT NULL,
    expired_at timestamp without time zone NOT NULL,
    fulfilled_at timestamp without time zone DEFAULT NULL,
    hospital_name varchar(200) NOT NULL,
    latitude decimal(10,8) DEFAULT NULL,
    longitude decimal(11,8) DEFAULT NULL,
    patient_name varchar(100) NOT NULL,
    status varchar(20) NOT NULL,
    units_required int NOT NULL,
    updated_at timestamp without time zone DEFAULT NULL,
    urgency varchar(20) NOT NULL,
    created_by bigint NOT NULL,
    version bigint DEFAULT 0,
    CONSTRAINT fk_br_user FOREIGN KEY (created_by) REFERENCES users (id)
);
CREATE INDEX idx_br_status ON blood_requests (status);
CREATE INDEX idx_br_blood_group ON blood_requests (blood_group);
CREATE INDEX idx_br_city ON blood_requests (city);
CREATE INDEX idx_br_urgency ON blood_requests (urgency);
CREATE INDEX idx_br_expired_at ON blood_requests (expired_at);
CREATE INDEX idx_br_created_at ON blood_requests (created_at);
CREATE INDEX idx_br_created_by ON blood_requests (created_by);

-- 5. Table donor_request_responses
CREATE TABLE donor_request_responses (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    notes varchar(500) DEFAULT NULL,
    notified_at timestamp without time zone DEFAULT NULL,
    responded_at timestamp without time zone DEFAULT NULL,
    status varchar(20) NOT NULL,
    updated_at timestamp without time zone DEFAULT NULL,
    donor_id bigint NOT NULL,
    request_id bigint NOT NULL,
    CONSTRAINT unique_donor_request UNIQUE (donor_id, request_id),
    CONSTRAINT fk_drr_donor FOREIGN KEY (donor_id) REFERENCES donor_profiles (id),
    CONSTRAINT fk_drr_request FOREIGN KEY (request_id) REFERENCES blood_requests (id)
);
CREATE INDEX idx_drr_donor ON donor_request_responses (donor_id);
CREATE INDEX idx_drr_request ON donor_request_responses (request_id);
CREATE INDEX idx_drr_status ON donor_request_responses (status);
CREATE INDEX idx_drr_notified_at ON donor_request_responses (notified_at);

-- 6. Table password_reset_tokens
CREATE TABLE password_reset_tokens (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamp without time zone DEFAULT NULL,
    expires_at timestamp without time zone NOT NULL,
    token varchar(200) NOT NULL UNIQUE,
    used boolean NOT NULL,
    user_id bigint NOT NULL,
    CONSTRAINT fk_prt_user FOREIGN KEY (user_id) REFERENCES users (id)
);
CREATE INDEX idx_prt_token ON password_reset_tokens (token);
CREATE INDEX idx_prt_user_id ON password_reset_tokens (user_id);
CREATE INDEX idx_prt_expiry ON password_reset_tokens (expires_at);

-- 7. Table donation_history
CREATE TABLE donation_history (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    blood_group varchar(20) NOT NULL,
    certificate_url varchar(255) DEFAULT NULL,
    created_at timestamp without time zone DEFAULT NULL,
    donation_date timestamp without time zone NOT NULL,
    hospital_name varchar(100) NOT NULL,
    is_verified boolean NOT NULL,
    units_donated int NOT NULL,
    updated_at timestamp without time zone DEFAULT NULL,
    request_id bigint NOT NULL,
    donor_id bigint NOT NULL,
    CONSTRAINT fk_dh_donor FOREIGN KEY (donor_id) REFERENCES donor_profiles (id),
    CONSTRAINT fk_dh_request FOREIGN KEY (request_id) REFERENCES blood_requests (id)
);
CREATE INDEX idx_donation_donor ON donation_history (donor_id);
CREATE INDEX idx_donation_request ON donation_history (request_id);
CREATE INDEX idx_donation_date ON donation_history (donation_date);
CREATE INDEX idx_donation_blood_group ON donation_history (blood_group);

-- 8. Table audit_logs
CREATE TABLE audit_logs (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    action varchar(100) NOT NULL,
    details text DEFAULT NULL,
    performed_by varchar(150) DEFAULT NULL,
    client_ip varchar(45) DEFAULT NULL,
    timestamp timestamp without time zone NOT NULL
);
CREATE INDEX idx_audit_timestamp ON audit_logs (timestamp);
